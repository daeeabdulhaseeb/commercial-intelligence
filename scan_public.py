"""Pre-push privacy scan: fails if any file that would be published contains a protected term.

Protected terms live OUTSIDE the repo history, in private/ (git-ignored):
  private/forbidden_extra.txt   one term per line (company names, system names, report codes ...)
  private/forbidden_auto.txt    generated by --refresh from the private data (customer, SE and project names)
  private/allowed.txt           reviewed generic phrases that may appear (e.g. 'residential tower')

  python scan_public.py --refresh private/config.json   # rebuild the auto list from company data
  python scan_public.py                                 # scan; exit code 1 if anything is found
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
SKIP_DIRS = {'.git', 'private', '__pycache__', 'vendor', '.ipynb_checkpoints'}
TEXT_EXT = {'.py', '.md', '.html', '.js', '.json', '.csv', '.txt', '.ps1', '.yml', '.yaml', '.toml', '.cfg', '.gz'}


def refresh(cfg_path):
    sys.path.insert(0, ROOT)
    from ci.build import load_private
    d = load_private(json.load(open(cfg_path)))
    s = d['snapshots']
    terms = set()
    for col, minlen in (('customer', 8), ('se', 6), ('project', 12)):
        for v in s[col].dropna().astype(str).unique():
            w = norm(v)
            if len(w) >= 2 and sum(ch.isalpha() for ch in ''.join(w)) >= minlen:
                terms.add(' '.join(w))
    path = os.path.join(ROOT, 'private', 'forbidden_auto.txt')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(sorted(terms)))
    print(f'{len(terms)} terms written to {path}')


def _lines(fn):
    p = os.path.join(ROOT, 'private', fn)
    if not os.path.exists(p):
        return []
    return [l.strip() for l in open(p, encoding='utf-8') if l.strip() and not l.startswith('#')]


def load_terms():
    allowed = {' '.join(norm(t)) for t in _lines('allowed.txt')}
    terms = {' '.join(norm(t)) for t in _lines('forbidden_extra.txt')}
    for t in _lines('forbidden_auto.txt'):
        w = norm(t)
        if len(w) >= 2 and sum(ch.isalpha() for ch in ''.join(w)) >= 6:
            terms.add(' '.join(w))
    return {t for t in terms if t and t not in allowed}


def read_text(p):
    if p.endswith('.gz'):
        import gzip
        return gzip.open(p, 'rt', encoding='utf-8', errors='ignore').read()
    return open(p, encoding='utf-8', errors='ignore').read()


def norm(t):
    return re.sub(r'[^0-9a-z&]+', ' ', t.casefold()).split()


def scan():
    terms = load_terms()
    if not terms:
        print('No protected terms found in private/ - create private/forbidden_extra.txt first.')
        return 2
    index = {}                                   # first word -> list of term word-tuples
    for t in terms:
        w = tuple(norm(t))
        if w:
            index.setdefault(w[0], []).append(w)
    hits = set()
    for dp, dns, fns in os.walk(ROOT):
        dns[:] = [d for d in dns if d not in SKIP_DIRS]
        for fn in fns:
            if os.path.splitext(fn)[1].lower() not in TEXT_EXT or fn == 'scan_public.py':
                continue
            p = os.path.join(dp, fn)
            txt = read_text(p)
            # CSV: check each field on its own so neighbouring fields don't form false phrases
            chunks = ([f for line in txt.splitlines() for f in line.split(',')]
                      if fn.endswith(('.csv', '.csv.gz')) else [txt])
            for ch in chunks:
                words = norm(ch)
                for i, w in enumerate(words):
                    for cand in index.get(w, ()):
                        if tuple(words[i:i + len(cand)]) == cand:
                            hits.add((os.path.relpath(p, ROOT), ' '.join(cand)))
    for f, t in sorted(hits)[:200]:
        print(f'  {f}: "{t}"')
    print(f'{len(terms)} protected terms checked - {len(hits)} hit(s).')
    return 1 if hits else 0


if __name__ == '__main__':
    if len(sys.argv) > 2 and sys.argv[1] == '--refresh':
        refresh(sys.argv[2])
    else:
        sys.exit(scan())
